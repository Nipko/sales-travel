const ALPHA2_CODES: ReadonlySet<string> = new Set(Object.values(ISO_ALPHA3_TO_ALPHA2));

/** Todos los alfa-2 oficiales, en orden alfabético de código. */
export const COUNTRY_CODES: readonly string[] = Object.freeze([...ALPHA2_CODES].sort());

/** ¿Es un alfa-2 oficialmente asignado? Exige mayúsculas: no normaliza. */
export function isCountryAlpha2(code: string): boolean {
  return ALPHA2_CODES.has(code);
}

/**
 * El alfa-2 de un país escrito en alfa-2 o alfa-3, sin distinguir mayúsculas ni espacios en los
 * bordes; `undefined` si no es un código oficial. Misma regla que `toIsoCountryAlpha2` del API.
 *
 * No adivina: un texto libre del CRM ("Colombia") no convierte y hay que pedírselo al vendedor.
 */
export function toCountryAlpha2(value: string): string | undefined {
  const trimmed = value.trim();
  // Sólo letras ASCII ANTES de pasar a mayúsculas: `toUpperCase` expande 'ß' a 'SS' (Sudán del
  // Sur), y eso sería inventar un país.
  if (!/^[A-Za-z]{2,3}$/.test(trimmed)) return undefined;
  const code = trimmed.toUpperCase();
  if (code.length === 2) return ALPHA2_CODES.has(code) ? code : undefined;
  return Object.prototype.hasOwnProperty.call(ISO_ALPHA3_TO_ALPHA2, code)
    ? ISO_ALPHA3_TO_ALPHA2[code]
    : undefined;
}
